#!/usr/bin/env node
// How much there is to find. A child zooming into a country should meet a
// handful of animals, not one scorpion — and Globe can only show what the
// authored data says, so a thin country is a data gap and nothing else.
//
//   node tools/geography/check-coverage.mjs            report and fail below target
//   node tools/geography/check-coverage.mjs --write    also write the worklist
//
// Writes docs/apps/globe-content-gaps.md: every country under target, with what
// it already has, so filling it needs no further research into what is missing.

import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const CONTENT_DIR = join(HERE, '..', '..', 'packages', 'geography', 'content')
const GENERATED_DIR = join(HERE, '..', '..', 'packages', 'geography', 'generated')
const DOC = join(HERE, '..', '..', 'docs', 'apps', 'globe-content-gaps.md')
const WRITE = process.argv.includes('--write')

/** What a country needs before it is worth zooming into. */
const TARGET_ANIMALS = 8
/** And the floor below which it is simply empty. */
const FLOOR_ANIMALS = 3

const read = async (name, dir = CONTENT_DIR) => JSON.parse(await readFile(join(dir, name), 'utf8'))
const englishName = (entry) => entry.names?.en ?? entry.name ?? entry.id

const source = await read('country-animals.json')
const countries = (await read('countries.json', GENERATED_DIR)).countries
const countryName = new Map(countries.map((country) => [country.id, country.name]))

const rows = Object.entries(source.countries)
  .map(([id, entry]) => ({
    id,
    name: countryName.get(id) ?? id,
    animals: (entry.animals ?? []).map(englishName),
    reviewed: entry.review?.state !== 'draft'
  }))
  .sort((a, b) => a.animals.length - b.animals.length || a.name.localeCompare(b.name))

const species = new Set(Object.values(source.countries).flatMap((entry) => (entry.animals ?? []).map((a) => a.id)))
const total = rows.reduce((sum, row) => sum + row.animals.length, 0)
const belowFloor = rows.filter((row) => row.animals.length < FLOOR_ANIMALS)
const belowTarget = rows.filter((row) => row.animals.length < TARGET_ANIMALS)

if (WRITE) {
  const lines = [
    '# Tiko Globe — countries that need more animals',
    '',
    'Generated by `node tools/geography/check-coverage.mjs --write`.',
    '',
    `A child zooming into a country should meet **at least ${TARGET_ANIMALS} animals**.`,
    `Right now ${belowTarget.length} of ${rows.length} countries are under that, and`,
    `${belowFloor.length} have fewer than ${FLOOR_ANIMALS}.`,
    '',
    'Across the whole world there are only',
    `**${species.size} distinct species** in ${total} placements, so the same animals keep`,
    'turning up. Malta is the shape to copy: 26 animals, each with a scientific',
    'name, a status and its own coordinates.',
    '',
    'Add to `packages/geography/content/country-animals.json`. Every entry needs an',
    '`id`, `names.en`, `i18nKey`, `importance` 1–10, and its own `lat`/`lon` inside',
    'the country. Only animals actually found there — a plausible-sounding animal',
    'in the wrong country is worse than an empty one.',
    '',
    '| Country | Has | Already listed |',
    '| --- | --- | --- |',
  ]
  for (const row of belowTarget) {
    lines.push(`| ${row.name} | ${row.animals.length} | ${row.animals.join(', ') || '—'} |`)
  }
  lines.push('')
  await writeFile(DOC, `${lines.join('\n')}\n`)
}

process.stdout.write(
  `coverage: ${total} placements over ${rows.length} countries ` +
  `(${(total / rows.length).toFixed(1)} each, ${species.size} distinct species)\n`
)
if (belowTarget.length > 0) {
  process.stdout.write(
    `${belowTarget.length} countries under ${TARGET_ANIMALS} animals, ` +
    `${belowFloor.length} under ${FLOOR_ANIMALS}: ${belowFloor.map((row) => `${row.name} (${row.animals.length})`).slice(0, 12).join(', ')}` +
    `${belowFloor.length > 12 ? ` and ${belowFloor.length - 12} more` : ''}\n`
  )
  process.exitCode = 1
}
