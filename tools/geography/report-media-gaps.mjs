#!/usr/bin/env node
// What Tiko Globe wants from the media library and cannot get.
//
//   node tools/geography/report-media-gaps.mjs
//
// Writes docs/apps/globe-media-gaps.md and prints a summary, ordered by how
// much each one matters: a landmark a child looks for from space outranks a
// beetle. Reads the authored files, where `mediaId` says which picture a
// subject should have — no picture, no mediaId, and the gap is real.

import { readFile, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const CONTENT_DIR = join(HERE, '..', '..', 'packages', 'geography', 'content')
const GAPS_FILE = join(HERE, '..', '..', 'packages', 'geography', 'generated', 'media-gaps.json')
const IMAGE_DIR = join(CONTENT_DIR, 'images')
const GENERATED_DIR = join(HERE, '..', '..', 'packages', 'geography', 'generated')
const DOC = join(HERE, '..', '..', 'docs', 'apps', 'globe-media-gaps.md')

const read = async (name, dir = CONTENT_DIR) => JSON.parse(await readFile(join(dir, name), 'utf8'))
const englishName = (entry) => entry.names?.en ?? entry.name ?? entry.id
const hasArtwork = (mediaId) => Boolean(mediaId) && existsSync(join(IMAGE_DIR, `${mediaId}.png`))

const cities = JSON.parse(await readFile(join(GENERATED_DIR, 'cities.json'), 'utf8')).items
const flagDir = join(CONTENT_DIR, 'flags')
const byCountry = await read('country-animals.json')
const ranges = await read('animal-districts.json')
const landmarkSource = await read('country-landmarks.json')
const peopleSource = await read('people.json')
const countries = (await read('countries.json', GENERATED_DIR)).countries
const countryName = new Map(countries.map((country) => [country.id, country.name]))

/** Animals with no picture, and the countries that wanted them. */
const wanted = new Map()
function want(entry, countryId) {
  if (hasArtwork(entry.mediaId)) return
  const existing = wanted.get(entry.id) ?? {
    id: entry.id,
    name: englishName(entry),
    importance: entry.importance ?? 10,
    countries: [],
    scientificName: entry.scientificName ?? null
  }
  existing.importance = Math.min(existing.importance, entry.importance ?? 10)
  if (countryId && !existing.countries.includes(countryId)) existing.countries.push(countryId)
  wanted.set(entry.id, existing)
}

for (const [countryId, entry] of Object.entries(byCountry.countries)) {
  for (const animal of entry.animals ?? []) want(animal, countryId)
}
for (const item of ranges.items) want(item, null)

const missingAnimals = [...wanted.values()].sort(
  (a, b) => a.importance - b.importance || b.countries.length - a.countries.length || a.name.localeCompare(b.name)
)

/** Landmarks with no picture. Still drawn, with their glyph — only the art is missing. */
const landmarks = []
for (const [countryId, entry] of Object.entries(landmarkSource.countries)) {
  for (const landmark of entry.landmarks ?? []) {
    if (hasArtwork(landmark.mediaId)) continue
    landmarks.push({
      id: landmark.id,
      name: englishName(landmark),
      country: countryId,
      importance: landmark.importance,
      lat: landmark.lat ?? null,
      lon: landmark.lon ?? null,
      glyph: landmark.glyph ?? null,
    })
  }
}
landmarks.sort((a, b) => a.importance - b.importance || a.name.localeCompare(b.name))

const totalLandmarks = Object.values(landmarkSource.countries)
  .reduce((total, entry) => total + (entry.landmarks?.length ?? 0), 0)

const band = (low, high) => landmarks.filter((item) => item.importance >= low && item.importance <= high)
const named = (id) => countryName.get(id) ?? id

// People: a person with no picture is not shown at all, exactly like an animal —
// a generic figure standing in for the Sámi would teach a child something false.
const peopleGaps = (peopleSource.items ?? [])
  .filter((person) => !hasArtwork(person.mediaId))
  .map((person) => ({
    id: person.id,
    name: person.name,
    era: person.era,
    importance: person.importance,
    countries: person.countries ?? [],
    note: person.note ?? null,
  }))
  .sort((a, b) => a.importance - b.importance || a.name.localeCompare(b.name))


const lines = [
  '# Tiko Globe — what the media library is missing',
  '',
  'Generated by `node tools/geography/report-media-gaps.mjs`.',
  '',
  'An **animal** with no picture is not shown at all — that country is simply one',
  'animal short. Globe does not substitute a different animal: a tortoise standing',
  'in for a sea turtle tells a child something false, and they have no way to know.',
  '',
  'A **landmark** with no picture is still on the globe, drawn with its glyph. The',
  'place is real either way; only the artwork is missing.',
  '',
  `At the time of writing: **${missingAnimals.length} animals**,`,
  `**${landmarks.length} of ${totalLandmarks} landmarks** and`,
  `**${peopleGaps.length} people** have no picture.`,
  '',
  '## Animals',
  '',
  'Most important first — importance 1 shows from space, 10 only at the closest',
  'zoom — then by how many countries are waiting on it.',
  '',
  '| Animal | Species | Importance | Wanted by |',
  '| --- | --- | --- | --- |',
]

for (const animal of missingAnimals) {
  const where = animal.countries.length === 0
    ? 'its world range'
    : animal.countries.slice(0, 6).map(named).join(', ') +
      (animal.countries.length > 6 ? ` +${animal.countries.length - 6} more` : '')
  lines.push(`| ${animal.name} | ${animal.scientificName ?? '—'} | ${animal.importance} | ${where} |`)
}

for (const [title, low, high, note] of [
  ['Landmarks — the famous ones', 1, 3, 'Visible from the whole-Earth view. These are the ones a child goes looking for.'],
  ['Landmarks — well known', 4, 6, 'Visible once a child is looking at a region.'],
  ['Landmarks — at country zoom', 7, 10, 'Often the only landmark that country has.'],
]) {
  lines.push('', `## ${title}`, '', note, '', '| Landmark | Country |', '| --- | --- |')
  for (const landmark of band(low, high)) lines.push(`| ${landmark.name} | ${named(landmark.country)} |`)
}

// Cities: only the ones a child meets first. Seven thousand towns without a
// picture is not a gap, it is the normal state of a map.
const cityGaps = cities
  .filter((city) => city.isCapital || city.importance <= 4)
  .filter((city) => !city.mediaId)
  .map((city) => ({
    id: city.id,
    name: city.name,
    country: city.country,
    countryName: named(city.country),
    importance: city.importance,
    isCapital: city.isCapital,
  }))
  .sort((a, b) => a.importance - b.importance || a.name.localeCompare(b.name))

// Flags: a country with no artwork falls back to the emoji, and 28 territories
// have neither.
const flagGaps = countries
  .filter((country) => !existsSync(join(flagDir, `${country.id}.png`)))
  .map((country) => ({ id: country.id, name: country.name }))
  .sort((a, b) => a.name.localeCompare(b.name))

await writeFile(GAPS_FILE, `${JSON.stringify({
  schemaVersion: 1,
  note: 'Built by tools/geography/report-media-gaps.mjs. Everything Globe would show a picture of and cannot. Ordered by importance, 1 being what a child sees from space.',
  howToUse: {
    title: 'Publish each picture to the Tiko media library under exactly the `expectedTitle` given here.',
    then: 'Run `node tools/geography/link-media.mjs --write` (animals and landmarks) or `node tools/geography/build-people.mjs --write` (people). Both match on the exact title, download a copy into packages/geography/content/images/<id>.png, and write the link into the authored data.',
    matching: 'Exact title only. A near match is deliberately refused: Globe shows the glyph perfectly well without a picture, and a wrong picture on a child\'s card is worse than none.',
    flags: 'Flags are not looked up by title — drop the file at `expectedFile`, named by the ISO3 code.',
  },
  summary: {
    animals: { missing: missingAnimals.length },
    landmarks: { missing: landmarks.length, of: totalLandmarks },
    cities: { missing: cityGaps.length, of: cities.filter((city) => city.isCapital || city.importance <= 4).length },
    people: { missing: peopleGaps.length, of: peopleSource.items?.length ?? 0 },
    flags: { missing: flagGaps.length, of: countries.length },
  },
  animals: missingAnimals.map((animal) => ({
    id: animal.id,
    // The title the picture has to carry in the media library for the next
    // link-media run to find it. It is the English name, exactly.
    expectedTitle: animal.name,
    name: animal.name,
    scientificName: animal.scientificName,
    importance: animal.importance,
    wantedBy: animal.countries,
    wantedByNames: animal.countries.map(named),
  })),
  landmarks: landmarks.map((landmark) => ({
    id: landmark.id,
    expectedTitle: landmark.name,
    name: landmark.name,
    country: landmark.country,
    countryName: named(landmark.country),
    importance: landmark.importance,
    lat: landmark.lat,
    lon: landmark.lon,
    glyph: landmark.glyph,
  })),
  cities: cityGaps.map((city) => ({ ...city, expectedTitle: city.name })),
  people: peopleGaps.map((person) => ({
    ...person,
    // People are filed under a bare slug, so the picture is looked up by the
    // person's name and by "<Name> Person", which is the shape the library
    // already uses for Sami Person, Inuit Person and the rest.
    expectedTitle: person.name,
    alsoAccepted: [`${person.name} Person`],
    countryNames: person.countries.map(named),
  })),
  flags: flagGaps.map((flag) => ({ ...flag, expectedFile: `content/flags/${flag.id}.png` })),
}, null, 2)}\n`)

lines.push(
  '',
  '## People',
  '',
  'Like an animal, a person with no picture is not shown at all: a generic figure',
  'standing in for the Sámi would teach a child something false.',
  '',
  '| Person | Era | Importance | Where |',
  '| --- | --- | --- | --- |',
)
for (const person of peopleGaps) {
  const where = person.countries.length === 0 ? '—' : person.countries.map(named).join(', ')
  lines.push(`| ${person.name} | ${person.era} | ${person.importance} | ${where} |`)
}

lines.push('')
await writeFile(DOC, `${lines.join('\n')}\n`)

process.stdout.write(
  `media gaps: ${missingAnimals.length} animals, ${landmarks.length} of ${totalLandmarks} landmarks, ` +
  `${cityGaps.length} cities worth a picture, ${peopleGaps.length} of ${peopleSource.items?.length ?? 0} people, ` +
  `${flagGaps.length} of ${countries.length} flags\n`
)
