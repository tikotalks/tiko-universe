#!/usr/bin/env node
/**
 * Generate the index of `@tiko/talk-packs` from the JSON files beside it.
 *
 * The packs are **data an app carries**, not something it fetches. That is the whole
 * point of this package: a child's tiles and the grammar that turns them into a
 * sentence both live in the app, so building a sentence never needs the network.
 *
 * Each locale is a **separate dynamic import**, so a bundler splits them: the app
 * ships all 54 and loads the one the child uses. In a Capacitor or native build they
 * are all on the device from the start.
 *
 * Usage:
 *   node tools/generate-talk-packs-index.mjs
 *   node tools/generate-talk-packs-index.mjs --check
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const PACKAGE = join(ROOT, 'packages/talk-packs')
const CHECK = process.argv.includes('--check')

const files = readdirSync(join(PACKAGE, 'data'))
  .filter((name) => /^[a-z]{2,3}-v\d+\.json$/.test(name))
  .sort()

const entries = files.map((file) => ({
  locale: file.replace(/-v\d+\.json$/, ''),
  file,
}))

const lines = [
  '// Generated by tools/generate-talk-packs-index.mjs — do not edit.',
  '//',
  '// One dynamic import per locale, so a bundler gives each pack its own chunk and an',
  '// app loads only the language in front of the child — while still carrying all of',
  '// them, because none of this should need the network.',
  '',
  "import type { LanguagePack } from '@tiko/talk-types'",
  '',
  '/** Every locale that has a pack. */',
  `export const packLocales = [${entries.map((entry) => `'${entry.locale}'`).join(', ')}] as const`,
  '',
  'export type PackLocale = typeof packLocales[number]',
  '',
  '/** The loaders, one chunk each. */',
  'const loaders: Record<string, () => Promise<{ default: unknown }>> = {',
  ...entries.map((entry) => `  ${JSON.stringify(entry.locale)}: () => import('../data/${entry.file}'),`),
  '}',
  '',
  '/** True where a pack exists for this locale. */',
  'export function hasPack(locale: string): boolean {',
  '  return language(locale) in loaders',
  '}',
  '',
  '/**',
  ' * Loads one language pack. The locale may carry a region ("nl-BE"); only the',
  ' * language part is used, and an unknown one throws rather than resolving to',
  ' * English silently — a caller that wants a fallback should ask for it.',
  ' */',
  'export async function loadPack(locale: string): Promise<LanguagePack> {',
  '  const code = language(locale)',
  '  const loader = loaders[code]',
  '  if (!loader) throw new Error(`no Talk pack for locale "${locale}"`)',
  '  const module = await loader()',
  '  return module.default as LanguagePack',
  '}',
  '',
  '/** The language part of a locale, lowercased. */',
  'function language(locale: string): string {',
  "  return locale.split('-')[0].toLowerCase()",
  '}',
  '',
  '/** The shared media map: one image per concept id, across every language. */',
  'export async function loadMediaMap(): Promise<Record<string, string>> {',
  "  const module = await import('../data/media-map.json')",
  '  return module.default as Record<string, string>',
  '}',
  '',
]

const target = join(PACKAGE, 'src/index.ts')
const contents = lines.join('\n')
const previous = existsSync(target) ? readFileSync(target, 'utf8') : null

if (previous === contents) {
  console.log('OK   packages/talk-packs/src/index.ts is up to date')
} else if (CHECK) {
  console.error('STALE packages/talk-packs/src/index.ts')
  process.exit(1)
} else {
  writeFileSync(target, contents)
  console.log(`Wrote packages/talk-packs/src/index.ts — ${entries.length} locales`)
}
