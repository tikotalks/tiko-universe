#!/usr/bin/env node
// Arlez project map: bundle ID -> product ID, and the Swift table built from it.
//
// A product ID is not a credential. The public client contract says so outright
// ("A product ID selects a destination; it is not a credential"), which is why
// the map is checked in and ships inside the apps.
//
// The Arlez API *key* is a different thing entirely — a founder secret that must
// never reach a customer application or a repository. Only `--refresh` touches
// the API, and it reads the key from ARLEZ_API_KEY in the environment. The
// default run and `--check` work purely from the checked-in JSON, so CI never
// needs the key and cannot leak one.
//
//   node tools/generate-arlez-projects.mjs            # JSON -> Swift
//   node tools/generate-arlez-projects.mjs --check    # fail if Swift is stale
//   ARLEZ_API_KEY=… node tools/generate-arlez-projects.mjs --refresh   # API -> JSON -> Swift

import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const jsonPath = join(root, 'packages/tikokit-ios/arlez-projects.json')
const swiftPath = join(root, 'packages/tikokit-ios/Sources/TikoKit/TikoArlezProjects.generated.swift')

const API = 'https://api.arlez.app'
const WORKSPACE = '81b1be07-f374-4a1c-8feb-a70756a704a6' // Tiko

const check = process.argv.includes('--check')
const refresh = process.argv.includes('--refresh')

async function refreshFromAPI() {
  const key = process.env.ARLEZ_API_KEY
  if (!key) {
    console.error('ARLEZ_API_KEY is not set. Create a key in the Arlez founder app and pass it in the environment.')
    console.error('Never commit it, never paste it into a prompt, and never put it in an app.')
    process.exit(1)
  }
  const response = await fetch(`${API}/v1/workspaces/${WORKSPACE}/projects`, {
    headers: { Authorization: `Bearer ${key}` }
  })
  if (!response.ok) throw new Error(`Arlez returned HTTP ${response.status}`)
  const { projects } = await response.json()

  // Only projects with a bundle ID can be resolved by an app at runtime; the web
  // projects have none, and an iOS project without one cannot be matched.
  const byBundle = {}
  for (const p of projects) {
    if (!p.bundleID) continue
    byBundle[p.bundleID] = { productID: p.productID, name: p.name, platform: p.platform }
  }
  const skipped = projects.filter((p) => !p.bundleID).map((p) => p.name)
  const map = { workspace: 'Tiko', workspaceID: WORKSPACE, projects: sortKeys(byBundle) }
  await writeFile(jsonPath, JSON.stringify(map, null, 2) + '\n')
  console.log(`refreshed ${Object.keys(byBundle).length} project(s) from Arlez`)
  if (skipped.length) console.log(`  no bundle ID, not mapped: ${skipped.join(', ')}`)
}

function sortKeys(o) {
  return Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)))
}

function renderSwift(map) {
  const rows = Object.entries(map.projects)
    .filter(([, p]) => p.platform === 'ios')
    .map(([bundleID, p]) => `        "${bundleID}": "${p.productID}", // ${p.name}`)
    .join('\n')

  return `// Generated by tools/generate-arlez-projects.mjs — do not edit.
// Source of truth: packages/tikokit-ios/arlez-projects.json
//
// A product ID selects a destination in Arlez. It is not a credential, which is
// why it can ship inside the app. The Arlez API key is a secret and is not here.

public enum TikoArlezProjects {

    /// Bundle identifier to Arlez product ID, for the iOS projects only.
    public static let productIDsByBundleID: [String: String] = [
${rows}
    ]

    /// The product ID for a bundle identifier, or nil when the app has no Arlez
    /// project yet — Support hides itself rather than offering a form that
    /// cannot be delivered.
    public static func productID(forBundleID bundleID: String?) -> String? {
        guard let bundleID else { return nil }
        return productIDsByBundleID[bundleID]
    }
}
`
}

async function main() {
  if (refresh) await refreshFromAPI()

  const map = JSON.parse(await readFile(jsonPath, 'utf8'))
  const swift = renderSwift(map)
  const current = await readFile(swiftPath, 'utf8').catch(() => null)

  if (check) {
    if (current !== swift) {
      console.error(`ERROR: ${swiftPath} is stale relative to arlez-projects.json — run node tools/generate-arlez-projects.mjs`)
      process.exit(1)
    }
    const ios = Object.values(map.projects).filter((p) => p.platform === 'ios').length
    console.log(`OK Arlez project table is up to date (${ios} iOS project(s))`)
    return
  }

  if (current !== swift) await writeFile(swiftPath, swift)
  const ios = Object.values(map.projects).filter((p) => p.platform === 'ios').length
  console.log(`wrote ${swiftPath.replace(root + '/', '')} — ${ios} iOS project(s)`)
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error)
  process.exit(1)
})
