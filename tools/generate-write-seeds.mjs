#!/usr/bin/env node
/**
 * Generate the D1 seed migration for Tiko Write glyph packs.
 *
 * Reads packages/write-glyphs/source/*.json (geometry) and source/names/*.json
 * (spoken names) and emits workers/content-api/migrations/0013_write_default_content.sql.
 *
 * Generated rather than hand-written because the source is 75 glyphs across
 * three packs and six locales: a hand-maintained migration would drift from the
 * packs within a week, and drift here means the app traces different geometry
 * than the repo says it does. `--check` is wired into `generated:check` so CI
 * fails on that drift instead of shipping it.
 *
 * Glyphs reuse the generic `content_items` model rather than bespoke tables:
 *   write_pack   — one per pack, carrying viewBox/guides/groups in metadata
 *   write_glyph  — one per glyph, child of its pack, carrying stroke geometry
 * That inherits the per-account override and publish machinery the other apps
 * already use. Names and phonics go in content_item_translations, which is what
 * that table is for.
 *
 * Usage:
 *   node tools/generate-write-seeds.mjs          # write the migration
 *   node tools/generate-write-seeds.mjs --check  # diff, exit 1 if stale
 */

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE_DIR = join(ROOT, 'packages/write-glyphs/source')
const NAMES_DIR = join(SOURCE_DIR, 'names')
const MIGRATION = join(ROOT, 'workers/content-api/migrations/0013_write_default_content.sql')

const CHECK_MODE = process.argv.includes('--check')

/** Escape for a single-quoted SQL literal. */
function sqlString(value) {
  return `'${String(value).replace(/'/g, "''")}'`
}

function sqlStringOrNull(value) {
  return value === undefined || value === null ? 'NULL' : sqlString(value)
}

function fail(message) {
  console.error(`ERROR: ${message}`)
  process.exit(1)
}

// ---------------------------------------------------------------------------
// Read the source
// ---------------------------------------------------------------------------

if (!existsSync(SOURCE_DIR)) fail(`missing ${SOURCE_DIR}`)

const packFiles = readdirSync(SOURCE_DIR)
  .filter((name) => name.endsWith('.json'))
  .sort()
if (packFiles.length === 0) fail(`no glyph packs in ${SOURCE_DIR}`)

const packs = packFiles.map((file) => JSON.parse(readFileSync(join(SOURCE_DIR, file), 'utf8')))

const localeFiles = existsSync(NAMES_DIR)
  ? readdirSync(NAMES_DIR).filter((n) => n.endsWith('.json')).sort()
  : []
const locales = localeFiles.map((file) => JSON.parse(readFileSync(join(NAMES_DIR, file), 'utf8')))

/** The spoken entry for a glyph in one locale, or undefined. */
function nameEntry(locale, pack, glyph) {
  if (pack.style === 'shape') return locale.shapes?.[glyph.id]
  if (pack.style === 'number') return locale.digits?.[glyph.char]
  return locale.letters?.[glyph.char.toLowerCase()]
}

// `en` is the source locale, so English content belongs on the base row rather
// than in a translation: getLocalizedContentItems in content-api deliberately
// skips the translation query when the requested language is English, so an `en`
// translation row would be dead data that never resolves.
const SOURCE_LOCALE = 'en'
const sourceNames = locales.find((l) => l.locale === SOURCE_LOCALE)
if (locales.length > 0 && !sourceNames) {
  fail(`no ${SOURCE_LOCALE}.json in ${NAMES_DIR} — the source locale must exist`)
}

// ---------------------------------------------------------------------------
// Emit
// ---------------------------------------------------------------------------

const ITEM_COLUMNS = [
  'id', 'template_id', 'title', 'slug', 'status', 'language_code', 'tags',
  'categories', 'data', 'app_id', 'type', 'parent_id', 'source_locale',
  'speech', 'sort_order', 'is_default', 'is_published', 'metadata_json',
]

function itemInsert(values) {
  return `INSERT INTO content_items (${ITEM_COLUMNS.join(', ')}) VALUES (${ITEM_COLUMNS.map((c) => values[c]).join(', ')});`
}

const lines = []
lines.push('-- Seed Tiko Write glyph packs into generic app content items.')
lines.push('-- GENERATED by tools/generate-write-seeds.mjs from packages/write-glyphs — do not edit.')
lines.push('-- A pack is a write_pack item; each glyph is a write_glyph child carrying its')
lines.push('-- stroke geometry in metadata_json. Names and phonics live in translations.')
lines.push('')
lines.push("DELETE FROM content_item_translations WHERE item_id IN (SELECT id FROM content_items WHERE app_id = 'write' AND owner_user_id IS NULL);")
lines.push("DELETE FROM content_items WHERE app_id = 'write' AND owner_user_id IS NULL;")
lines.push('')

let glyphCount = 0
let translationCount = 0

packs.forEach((pack, packIndex) => {
  const packRowId = `write_${pack.packId}`
  const packMeta = JSON.stringify({
    packSchemaVersion: pack.packSchemaVersion,
    packVersion: pack.packVersion,
    style: pack.style,
    viewBox: pack.viewBox,
    ...(pack.guides ? { guides: pack.guides } : {}),
    ...(pack.groups ? { groups: pack.groups } : {}),
  })

  lines.push(`-- ${pack.packId}: ${pack.glyphs.length} glyphs`)
  lines.push(itemInsert({
    id: sqlString(packRowId),
    template_id: sqlString('write.pack'),
    title: sqlString(pack.packId),
    slug: sqlString(packRowId),
    status: sqlString('published'),
    language_code: sqlString('en'),
    tags: 'NULL',
    categories: sqlString('["write"]'),
    data: sqlString(packMeta),
    app_id: sqlString('write'),
    type: sqlString('write_pack'),
    parent_id: 'NULL',
    source_locale: sqlString('en'),
    speech: 'NULL',
    sort_order: String(packIndex),
    is_default: '1',
    is_published: '1',
    metadata_json: sqlString(packMeta),
  }))

  for (const glyph of pack.glyphs) {
    const glyphRowId = `write_${pack.packId}_${glyph.id}`
    const source = sourceNames ? nameEntry(sourceNames, pack, glyph) : undefined
    const glyphMeta = JSON.stringify({
      glyphId: glyph.id,
      packId: pack.packId,
      groupId: glyph.groupId,
      strokes: glyph.strokes,
      strokeOrderStrict: glyph.strokeOrderStrict ?? true,
      ...(source?.sound === undefined ? {} : { sound: source.sound }),
      ...(source?.word === undefined ? {} : { word: source.word }),
    })
    lines.push(itemInsert({
      id: sqlString(glyphRowId),
      template_id: sqlString('write.glyph'),
      title: sqlString(glyph.char),
      slug: sqlString(glyphRowId),
      status: sqlString('published'),
      language_code: sqlString('en'),
      tags: 'NULL',
      categories: sqlString('["write"]'),
      data: sqlString(glyphMeta),
      app_id: sqlString('write'),
      type: sqlString('write_glyph'),
      parent_id: sqlString(packRowId),
      source_locale: sqlString('en'),
      // The tile face is the character; the voice says the name. `title` stays
      // the character in every language so a Dutch tile still reads "A".
      speech: sqlStringOrNull(source?.name),
      sort_order: String(glyph.sortOrder),
      is_default: '1',
      is_published: '1',
      metadata_json: sqlString(glyphMeta),
    }))
    glyphCount += 1
  }
  lines.push('')
})

// Translations: the spoken name per locale. `speech` is what the voice says;
// the phoneme and example word ride along in metadata so a parent can switch
// the app between name, sound and word without another round trip.
const translated = locales.filter((l) => l.locale !== SOURCE_LOCALE)
if (translated.length > 0) {
  lines.push('-- Spoken names, phonics and example words, per non-source locale.')
  lines.push('-- `title` is deliberately NULL: it would override the glyph character,')
  lines.push('-- and a Dutch tile must still read "A" rather than "aa".')
  for (const locale of translated) {
    for (const pack of packs) {
      for (const glyph of pack.glyphs) {
        const entry = nameEntry(locale, pack, glyph)
        if (!entry) continue
        const meta = JSON.stringify({
          ...(entry.sound === undefined ? {} : { sound: entry.sound }),
          ...(entry.word === undefined ? {} : { word: entry.word }),
        })
        lines.push(
          `INSERT INTO content_item_translations (item_id, locale, title, speech, metadata_json) VALUES (${[
            sqlString(`write_${pack.packId}_${glyph.id}`),
            sqlString(locale.locale),
            'NULL',
            sqlString(entry.name),
            sqlStringOrNull(meta === '{}' ? null : meta),
          ].join(', ')});`
        )
        translationCount += 1
      }
    }
  }
  lines.push('')
}

const output = lines.join('\n')

// ---------------------------------------------------------------------------

if (CHECK_MODE) {
  const existing = existsSync(MIGRATION) ? readFileSync(MIGRATION, 'utf8') : null
  if (existing === null) {
    fail(`${MIGRATION} does not exist — run node tools/generate-write-seeds.mjs`)
  }
  if (existing !== output) {
    fail(
      `${MIGRATION} is stale relative to packages/write-glyphs — run node tools/generate-write-seeds.mjs`
    )
  }
  console.log(
    `write seeds up to date — ${packs.length} pack(s), ${glyphCount} glyphs, ${translationCount} translations`
  )
} else {
  writeFileSync(MIGRATION, output)
  console.log(
    `wrote ${MIGRATION.replace(ROOT + '/', '')} — ${packs.length} pack(s), ${glyphCount} glyphs, ${translationCount} translations`
  )
}
